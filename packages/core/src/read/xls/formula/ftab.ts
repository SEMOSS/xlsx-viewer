/** Parse `index NAME n` / `index NAME min-max` entries separated by `;` or line breaks. */
function parseFunctionTable(text: string): Map<number, FtabEntry> {
	const table = new Map<number, FtabEntry>();
	for (const item of text.split(/[;\n]/)) {
		const parts = item.trim().split(/\s+/);
		if (parts.length < 2) {
			continue;
		}
		const [min, max] = (parts[2] ?? '0').split('-').map(Number);
		table.set(Number(parts[0]), { name: parts[1], min, max: max ?? min });
	}
	return table;
}

