/** Series element sequence for a plot container. */
export function seriesOrderKey(container: string): string {
	switch (container) {
		case 'barChart':
		case 'bar3DChart':
			return 'barSer';
		case 'lineChart':
		case 'line3DChart':
		case 'stockChart':
			return 'lineSer';
		case 'pieChart':
		case 'pie3DChart':
		case 'doughnutChart':
		case 'ofPieChart':
			return 'pieSer';
		case 'areaChart':
		case 'area3DChart':
			return 'areaSer';
		case 'scatterChart':
			return 'scatterSer';
		case 'radarChart':
			return 'radarSer';
		case 'bubbleChart':
			return 'bubbleSer';
		default:
			return 'surfaceSer';
	}
}
