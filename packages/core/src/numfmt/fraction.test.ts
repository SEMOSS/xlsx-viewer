import { describe, expect, it } from 'vitest';

import { formatValue } from './index';
import { approximateFraction } from './render-fraction';

const text = (value: number, code: string) => formatValue(value, code).text;

describe('approximateFraction', () => {
	it.each([
		[0.5, 9, [1, 2]],
		[0.3, 9, [2, 7]],
		[0.1, 9, [1, 9]],
		[0.06, 9, [1, 9]],
		[0.001, 9, [0, 1]],
		[0.14159265358979, 9, [1, 7]],
		[0.14159265358979, 99, [14, 99]],
		[0.14159265358979, 999, [16, 113]],
		[0.123, 99, [8, 65]],
		[2.5, 9, [5, 2]],
		[0, 9, [0, 1]],
		[0.99, 9, [1, 1]],
	])('%s with denominators up to %i', (x, maxDen, expected) => {
		expect(approximateFraction(x, maxDen)).toEqual(expected);
	});
});

describe('fraction formats', () => {
	it.each([
		['# ?/?', 1.5, '1 1/2'],
		['# ?/?', 0.5, ' 1/2'],
		['# ?/?', 0.75, ' 3/4'],
		['# ?/?', 3, '3    '],
		['# ?/?', 0, '0    '],
		['# ?/?', 0.3, ' 2/7'],
		['# ?/?', 0.1, ' 1/9'],
		['# ?/?', 0.66, ' 2/3'],
		['# ?/?', 1.25, '1 1/4'],
		['# ?/?', -1.25, '-1 1/4'],
		['# ?/?', 2.5, '2 1/2'],
		['# ?/?', 3.14159, '3 1/7'],
		['# ?/?', 0.99, '1    '],
		['# ?/?', 0.001, '0    '],
		['# ??/??', Math.PI, '3 14/99'],
		['# ??/??', 1.25, '1  1/4 '],
		['# ??/??', 0.5, '  1/2 '],
		['# ??/??', 0.123, '  8/65'],
		['# ??/??', 2, '2      '],
		['# ???/???', Math.PI, '3  16/113'],
		['# ???/???', 0.5, '   1/2  '],
		['?/?', 1.5, '3/2'],
		['?/?', 0.5, '1/2'],
		['?/?', 2, '2/1'],
		['?/?', 0, '0/1'],
		['??/??', 0.75, ' 3/4 '],
		['# ?/2', 1.25, '1 1/2'],
		['# ?/2', 1.24, '1    '],
		['# ?/4', 1.3, '1 1/4'],
		['# ?/4', 0.5, ' 2/4'],
		['# ?/8', 0.5, ' 4/8'],
		['# ?/8', 1.0625, '1 1/8'],
		['# ?/8', 2.999, '3    '],
		['# ??/16', 1.0625, '1  1/16'],
		['# ??/16', 0.5, '  8/16'],
		['# ?/10', 0.3, ' 3/10'],
		['# ??/100', 0.333, ' 33/100'],
		['# ??/100', 0.3, ' 30/100'],
		['# ??/100', 1.255, '1 26/100'],
		['?/8', 1.5, '12/8'],
		['0 ?/?', 0.5, '0 1/2'],
		['#,##0 ?/?', 1234567.5, '1,234,567 1/2'],
		['# ?/? "in"', 1.5, '1 1/2 in'],
		['# ?/?;(# ?/?)', -1.5, '(1 1/2)'],
	])('%s with %s -> "%s"', (code, value, expected) => {
		expect(text(value, code)).toBe(expected);
	});

	it('keeps the minus sign in front of the whole format', () => {
		expect(text(-0.5, '# ?/?')).toBe('- 1/2');
		expect(text(-2, '?/?')).toBe('-2/1');
	});

	it('leaves text alone', () => {
		expect(text(Number.NaN, '# ?/?')).toBe('#NUM!');
		expect(formatValue('abc', '# ?/?').text).toBe('abc');
	});
});
