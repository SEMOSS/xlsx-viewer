describe('repeat fill', () => {
	it('splits the text around the first fill', () => {
		expect(formatValue(5, '0*-')).toEqual({
			text: '5',
			fill: { before: '5', char: '-', after: '' },
		});
		expect(formatValue(5, '*.0')).toEqual({
			text: '5',
			fill: { before: '', char: '.', after: '5' },
		});
		expect(formatValue(-5, '"$"* 0')).toEqual({
			text: '-$5',
			fill: { before: '-$', char: ' ', after: '5' },
		});
		expect(formatValue(5, '*a0*b').fill).toEqual({ before: '', char: 'a', after: '5' });
	});
});

